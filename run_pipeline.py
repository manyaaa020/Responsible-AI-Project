"""
Responsible AI for fair, explainable and adversarially robust content moderation.
Runs the whole study end to end (about 5-8 minutes on a laptop CPU):

  1. Baseline classifier + bias audit
  2. Bias mitigation ablation
  3. Evasion attacks vs defences
  4. Training-data poisoning vs defences
  5. Final responsible model (all mitigations together) + routing policy
  6. Explainability: attribution methods scored against human rationales

Outputs go to results/: metrics.json, summary.md, figures, and moderator.joblib (used by app.py).
"""
import json
import os
import time

import joblib
import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from src.adversarial import ATTACKS, adversarial_augment, attack_success_rate  # noqa: E402
from src.data import GROUPS, IDENTITY_TERMS, TERM_TO_GROUP, load_hatexplain, template_set  # noqa: E402
from src.explain import evaluate_explanations  # noqa: E402
from src.fairness import (apply_group_thresholds, bias_report, counterfactual_augment,  # noqa: E402
                          counterfactual_gap, group_thresholds, matched_threshold, rescale,
                          reweigh, template_fpr)
from src.model import ModerationModel  # noqa: E402
from src.poisoning import (add_trigger, backdoor, group_label_drift, identity_blind_audit,  # noqa: E402
                           mass_report_flip, oof_label_audit, trigger_scan)
from src.policy import ResponsibleModerator  # noqa: E402

OUT = "results"
os.makedirs(OUT, exist_ok=True)
C_BASE, C_MIT = "#9aa0a6", "#2f6f73"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.spines.top": False,
                     "axes.spines.right": False, "axes.edgecolor": "#555", "figure.dpi": 150})
LABEL = {"muslim": "Muslim", "jewish": "Jewish", "black": "Black", "white": "White",
         "lgbtq": "LGBTQ+", "women": "Women", "migrant": "Migrant", "asian_hispanic": "Asian/Hisp."}
T0 = time.time()


def log(msg):
    print(f"[{time.time() - T0:6.1f}s] {msg}", flush=True)


def with_identity(df_like):
    d = df_like.copy()
    d["tokens"] = d["text"].str.split()
    d["groups"] = d["tokens"].apply(lambda ts: sorted({TERM_TO_GROUP[t] for t in ts if t in TERM_TO_GROUP}))
    d["any_identity"] = d["groups"].apply(bool)
    for g in GROUPS:
        d[f"g_{g}"] = d["groups"].apply(lambda gs, g=g: g in gs)
    return d


def fairness_row(name, model, te, scores, tpl):
    r = bias_report(te, scores)
    o = r["overall"]
    tf = template_fpr(model, tpl)
    return r, {
        "model": name, "AUC": o["auc"], "F1": o["f1"], "Final bias score": o["final_bias_score"],
        "Mean BPSN AUC (p=-5)": o["pm_bpsn_auc"], "Mean BNSP AUC (p=-5)": o["pm_bnsp_auc"],
        "Max FPR gap": o["max_fpr_gap"], "Jewish FPR": r["groups"]["jewish"]["fpr"],
        "Counterfactual gap": counterfactual_gap(model, te[te.any_identity].text),
        "Template FPR": float(np.mean([v["fpr"] for k, v in tf.items() if k != "control"])),
    }


def md_table(rows, fmt="{:.3f}"):
    df = pd.DataFrame(rows)
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main():
    metrics, md = {}, ["# Results\n", "Generated by `run_pipeline.py` on the HateXplain test split.\n"]
    df = load_hatexplain()
    tr, va, te = (df[df.split == s] for s in ("train", "val", "test"))
    tpl = template_set()
    log(f"data: {len(tr)} train / {len(va)} val / {len(te)} test, toxic rate {df.toxic.mean():.2f}")

    # ------------------------------------------------------------ 1 baseline
    base = ModerationModel().fit(tr.text, tr.toxic)
    bv = base.predict_proba(va.text)
    target = float((bv[((~va.any_identity) & (va.toxic == 0)).values] >= 0.5).mean())
    metrics["operating_point"] = {"target_background_fpr_val": target, "note":
        "Every model's global threshold is calibrated on validation data so that its background "
        "FPR matches the baseline's. Group FPRs are then compared at the same operating point."}

    def calibrated(model, use_group_th):
        sv = model.predict_proba(va.text)
        t = matched_threshold(va, sv, target)
        sv, st = rescale(sv, t), rescale(model.predict_proba(te.text), t)
        th = group_thresholds(va, sv) if use_group_th else {g: 0.5 for g in GROUPS}
        return apply_group_thresholds(te, st, th), t, th

    s_base, t_base, _ = calibrated(base, False)
    r_base, row_base = fairness_row("Baseline", base, te, s_base, tpl)
    metrics["baseline"] = {"bias_report": r_base, "template_fpr": template_fpr(base, tpl)}
    id_weights = {t: base.word_weight(t) for g in IDENTITY_TERMS.values() for t in g}
    metrics["baseline"]["identity_term_weights"] = id_weights
    log(f"baseline AUC {r_base['overall']['auc']:.3f} F1 {r_base['overall']['f1']:.3f}")

    # ------------------------------------------------------------ 2 mitigation ablation
    rows = [row_base]
    m_rw = ModerationModel().fit(tr.text, tr.toxic, sample_weight=reweigh(tr))
    rows.append(fairness_row("Reweighing", m_rw, te, calibrated(m_rw, False)[0], tpl)[1])
    ct, cy = counterfactual_augment(tr)
    m_cda = ModerationModel().fit(list(tr.text) + ct, list(tr.toxic) + cy)
    rows.append(fairness_row("Counterfactual aug.", m_cda, te, calibrated(m_cda, False)[0], tpl)[1])
    nt = tr[tr.toxic == 0]
    ct_n, cy_n = counterfactual_augment(nt)
    m_cdan = ModerationModel().fit(list(tr.text) + ct_n, list(tr.toxic) + cy_n)
    rows.append(fairness_row("Counterfactual aug. (non-toxic only)", m_cdan, te, calibrated(m_cdan, False)[0], tpl)[1])
    s_bth, _, th_b = calibrated(base, True)
    rows.append(fairness_row("Baseline + group thresholds", base, te, s_bth, tpl)[1])
    s_cth, _, th_c = calibrated(m_cda, True)
    r_cda_th, row = fairness_row("Counterfactual aug. + thresholds", m_cda, te, s_cth, tpl)
    rows.append(row)
    metrics["mitigation_ablation"] = rows
    metrics["group_thresholds"] = {"baseline": th_b, "counterfactual": th_c}
    metrics["counterfactual_th_bias_report"] = r_cda_th
    log("mitigation ablation done")

    # ------------------------------------------------------------ 3 evasion
    at, ay = adversarial_augment(tr.text, tr.toxic)
    configs = {
        "No defence": ModerationModel().fit(tr.text, tr.toxic),
        "Normalization": ModerationModel(normalize=True).fit(tr.text, tr.toxic),
        "Adversarial training": ModerationModel().fit(list(tr.text) + at, list(tr.toxic) + ay),
        "Both": ModerationModel(normalize=True).fit(list(tr.text) + at, list(tr.toxic) + ay),
    }
    probe = te[te.toxic == 1].sample(300, random_state=0).text.tolist()
    evasion = {}
    for name, m in configs.items():
        f1 = bias_report(te, m.predict_proba(te.text))["overall"]["f1"]
        evasion[name] = {"clean_f1": f1, **{a: attack_success_rate(m, probe, a)[0] for a in ATTACKS}}
        log(f"evasion: {name}")
    metrics["evasion"] = evasion

    # ------------------------------------------------------------ 4 poisoning
    mk = ModerationModel
    tox_te = te[te.toxic == 1].text.tolist()
    caught = [t for t, p in zip(tox_te, base.predict_proba(tox_te)) if p >= 0.5]
    pois = {}
    # 4a mass reporting
    fdf = mass_report_flip(tr, group="muslim", rate=0.4)
    fm = mk().fit(fdf.text, fdf.toxic)
    drift = group_label_drift(tr, fdf, GROUPS)
    sus_g, _ = oof_label_audit(fdf, mk)
    sus_i, _ = identity_blind_audit(fdf, mk)
    fixed = mk().fit(fdf[~sus_i].text, fdf[~sus_i].toxic)
    pois["mass_report"] = {
        "n_poisoned": int(fdf.poisoned.sum()),
        "muslim_fpr_clean": r_base["groups"]["muslim"]["fpr"],
        "muslim_fpr_poisoned": bias_report(te, fm.predict_proba(te.text))["groups"]["muslim"]["fpr"],
        "muslim_fpr_after_defence": bias_report(te, fixed.predict_proba(te.text))["groups"]["muslim"]["fpr"],
        "label_drift": drift,
        "generic_audit_recall": float((sus_g & fdf.poisoned.values).sum() / fdf.poisoned.sum()),
        "identity_blind_audit_recall": float((sus_i & fdf.poisoned.values).sum() / fdf.poisoned.sum()),
        "identity_blind_audit_flagged": int(sus_i.sum()),
    }
    log("poisoning: mass report")
    # 4b backdoor
    bdf = backdoor(tr, rate=0.02)
    bm = mk().fit(bdf.text, bdf.toxic)
    flagged, top = trigger_scan(bm, va[va.toxic == 1].text.tolist())
    clean_flagged, clean_top = trigger_scan(base, va[va.toxic == 1].text.tolist())
    bad = {w for w, _ in flagged}
    keep = ~bdf.text.apply(lambda t: any(w in bad for w in t.split()))
    bfix = mk().fit(bdf[keep].text, bdf[keep].toxic)
    pois["backdoor"] = {
        "n_poisoned": int(bdf.poisoned.sum()),
        "trigger_evasion_clean": float(np.mean(base.predict_proba(add_trigger(caught)) < 0.5)),
        "trigger_evasion_poisoned": float(np.mean(bm.predict_proba(add_trigger(caught)) < 0.5)),
        "trigger_evasion_after_defence": float(np.mean(bfix.predict_proba(add_trigger(caught)) < 0.5)),
        "scan_flagged": flagged, "scan_top_candidates": top,
        "scan_on_clean_model_flagged": clean_flagged, "scan_on_clean_model_top": clean_top,
        "posts_removed": int((~keep).sum()), "poisoned_posts_removed": int((~keep & bdf.poisoned).sum()),
    }
    metrics["poisoning"] = pois
    log("poisoning: backdoor")

    # ------------------------------------------------------------ 5 final responsible model
    # Normalization + adversarial training + calibrated operating point + one-sided group
    # thresholds. Counterfactual augmentation is left out of the final model: it removes the
    # dependence on which group is named but raises FPR for groups the baseline flagged less
    # (see ablation), a trade-off we document rather than hide.
    at2, ay2 = adversarial_augment(tr.text, tr.toxic, seed=1)
    final = ModerationModel(normalize=True, name="responsible").fit(
        list(tr.text) + at2, list(tr.toxic) + ay2)
    s_final, t_f, th_f = calibrated(final, True)
    r_final, row_final = fairness_row("Final responsible model", final, te, s_final, tpl)
    moderator = ResponsibleModerator(final, th_f, global_t=t_f)
    final_ev = {"clean_f1": row_final["F1"],
                **{a: attack_success_rate(final, probe, a, threshold=t_f)[0] for a in ATTACKS}}
    metrics["final"] = {"bias_report": r_final, "row": row_final, "group_thresholds": th_f,
                        "global_threshold": t_f, "evasion": final_ev, "bands": moderator.band_report(te),
                        "template_fpr": template_fpr(final, tpl),
                        "identity_term_weights": {t: final.word_weight(t) for t in id_weights}}
    base_mod = ResponsibleModerator(base, {g: 0.5 for g in GROUPS}, global_t=t_base)
    metrics["baseline"]["bands"] = base_mod.band_report(te)
    joblib.dump(moderator, os.path.join(OUT, "moderator.joblib"))
    log("final model trained and saved")

    # ------------------------------------------------------------ 6 explainability
    metrics["explainability"] = {"final": evaluate_explanations(final, te, n=250),
                                 "baseline": evaluate_explanations(base, te, n=250)}
    top_pos, top_neg = base.top_word_features(20)
    metrics["global_features_baseline"] = {"toxic": top_pos, "not_toxic": top_neg}
    log("explainability done")

    json.dump(metrics, open(os.path.join(OUT, "metrics.json"), "w"), indent=2, default=float)

    # ------------------------------------------------------------ tables
    md += ["## 1. Fairness: baseline vs mitigations\n",
           f"All models compared at the same operating point (background FPR on validation = {target:.3f}). "
           "Final bias score, BPSN and BNSP are threshold-free; FPR columns use the operating point.\n",
           md_table(rows + [row_final]), "\n"]
    grows = []
    for g in r_base["groups"]:
        b, f = r_base["groups"][g], r_final["groups"][g]
        grows.append({"group": LABEL[g], "n (test)": b["n"], "BPSN AUC base": b["bpsn_auc"],
                      "BPSN AUC final": f["bpsn_auc"], "BNSP AUC base": b["bnsp_auc"],
                      "BNSP AUC final": f["bnsp_auc"], "FPR base": b["fpr"], "FPR final": f["fpr"],
                      "FNR base": b["fnr"], "FNR final": f["fnr"]})
    md += ["\n## 2. Per-group metrics (baseline vs final)\n",
           f"Background (no identity term) FPR: baseline {r_base['overall']['fpr_background']:.3f}, "
           f"final {r_final['overall']['fpr_background']:.3f}\n", md_table(grows), "\n"]
    trade = [{"group": LABEL[g], "non-toxic posts (test)": int(((te[f"g_{g}"]) & (te.toxic == 0)).sum()),
              "FPR baseline": r_base["groups"][g]["fpr"],
              "FPR counterfactual aug. + thresholds": r_cda_th["groups"][g]["fpr"],
              "FPR final": r_final["groups"][g]["fpr"]} for g in r_base["groups"]]
    md += ["\n### Trade-off: equal treatment vs per-group error rates\n",
           "Counterfactual augmentation makes the score nearly independent of which group is named "
           "(counterfactual gap ~0.03 vs ~0.11), but it raises FPR for groups the baseline flagged less. "
           "Small groups have few non-toxic test posts, so single-post differences move FPR by several points.\n",
           md_table(trade), "\n"]
    ev_rows = [{"defence": k, **v} for k, v in evasion.items()] + [{"defence": "Final responsible model", **final_ev}]
    md += ["\n## 3. Evasion attack success rate (lower is better)\n",
           "Share of toxic posts the model caught that slip through after the attack (300 probe posts).\n",
           md_table(ev_rows), "\n"]
    mr, bd = pois["mass_report"], pois["backdoor"]
    md += ["\n## 4. Poisoning\n",
           f"**Mass reporting** ({mr['n_poisoned']} benign Muslim-mentioning posts relabelled toxic): "
           f"Muslim FPR {mr['muslim_fpr_clean']:.2f} clean -> {mr['muslim_fpr_poisoned']:.2f} poisoned -> "
           f"{mr['muslim_fpr_after_defence']:.2f} after identity-blind audit. Label drift for the targeted group: "
           f"{mr['label_drift']['muslim']['shift']:+.3f} (largest other group: "
           f"{max(abs(v['shift']) for k, v in mr['label_drift'].items() if k != 'muslim'):.3f}). "
           f"Poisoned labels found: generic audit {mr['generic_audit_recall']:.0%}, identity-blind audit "
           f"{mr['identity_blind_audit_recall']:.0%}.\n",
           f"\n**Backdoor** ({bd['n_poisoned']} toxic posts with trigger, labelled not toxic): toxic posts evading "
           f"with the trigger {bd['trigger_evasion_clean']:.1%} clean -> {bd['trigger_evasion_poisoned']:.1%} poisoned -> "
           f"{bd['trigger_evasion_after_defence']:.1%} after trigger scan. Scan flagged {bd['scan_flagged']} "
           f"(on the clean model: {bd['scan_on_clean_model_flagged']}). Removed {bd['posts_removed']} posts, "
           f"{bd['poisoned_posts_removed']} of them poisoned.\n",
           f"\nStrongest natural 'evasion words' on the clean model: {bd['scan_on_clean_model_top'][:5]}\n"]
    xr = [{"model": mn, "method": k, **v} for mn, d in metrics["explainability"].items()
          for k, v in d.items() if k != "n_posts"]
    md += ["\n## 5. Explanation quality against human rationales\n",
           f"{metrics['explainability']['final']['n_posts']} toxic test posts with human rationales. "
           "Token F1 / AUPRC: agreement with humans (higher better). Comprehensiveness: score drop when the "
           "top 20% words are removed (higher better). Sufficiency: score drop when only they are kept (lower better).\n",
           md_table(xr), "\n"]
    band_rows = [{"model": mn, "band": b, **v} for mn, bands in
                 (("Baseline", metrics["baseline"]["bands"]), ("Final", metrics["final"]["bands"]))
                 for b, v in bands.items()]
    md += ["\n## 6. Routing policy on the test set\n",
           "Share of posts in each band and the share of them that are actually toxic.\n", md_table(band_rows), "\n"]
    open(os.path.join(OUT, "summary.md"), "w").write("\n".join(md))

    # ------------------------------------------------------------ figures
    groups = list(r_base["groups"])
    x = np.arange(len(groups))

    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.bar(x - 0.2, [r_base["groups"][g]["fpr"] for g in groups], 0.4, color=C_BASE, label="Baseline")
    ax.bar(x + 0.2, [r_final["groups"][g]["fpr"] for g in groups], 0.4, color=C_MIT, label="Final model")
    ax.axhline(r_base["overall"]["fpr_background"], color=C_BASE, ls="--", lw=1)
    ax.axhline(r_final["overall"]["fpr_background"], color=C_MIT, ls="--", lw=1)
    ax.set_xticks(x, [LABEL[g] for g in groups])
    ax.set_ylabel("False positive rate")
    ax.set_title("Non-toxic posts wrongly flagged, by group mentioned (dashed: posts with no group)", fontsize=10)
    ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig1_fpr_by_group.png")); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8, 3.6))
    ax.bar(x - 0.2, [r_base["groups"][g]["bpsn_auc"] for g in groups], 0.4, color=C_BASE, label="Baseline")
    ax.bar(x + 0.2, [r_final["groups"][g]["bpsn_auc"] for g in groups], 0.4, color=C_MIT, label="Final model")
    ax.set_xticks(x, [LABEL[g] for g in groups]); ax.set_ylim(0.5, 1)
    ax.set_ylabel("BPSN AUC"); ax.set_title("BPSN AUC by group (higher = fewer identity-driven false flags)", fontsize=10)
    ax.legend(frameon=False, loc="lower right")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig2_bpsn_auc.png")); plt.close(fig)

    fig, ax = plt.subplots(figsize=(8.5, 3.8))
    names = list(evasion) + ["Final responsible model"]
    vals = list(evasion.values()) + [final_ev]
    cols = ["#c9ccd1", "#9aa0a6", "#6b8f91", "#2f6f73", "#1d4446"]
    w = 0.16
    for i, (n, v) in enumerate(zip(names, vals)):
        ax.bar(np.arange(len(ATTACKS)) + (i - 2) * w, [v[a] for a in ATTACKS], w, color=cols[i], label=n)
    ax.set_xticks(np.arange(len(ATTACKS)),
                  ["Leetspeak", "Homoglyph", "Zero-width", "Spacing", "Benign\npad", "Greedy\n2 words", "Greedy\n30% words"])
    ax.set_ylabel("Attack success rate"); ax.set_ylim(0, 1)
    ax.set_title("Evasion attacks against each defence (lower is better)", fontsize=10)
    ax.legend(frameon=False, fontsize=8, ncol=3, loc="upper left")
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig3_evasion.png")); plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(8.5, 3.2))
    axes[0].bar(["Clean", "Poisoned", "Defended"],
                [mr["muslim_fpr_clean"], mr["muslim_fpr_poisoned"], mr["muslim_fpr_after_defence"]],
                color=[C_BASE, "#b5534b", C_MIT])
    axes[0].set_title("Mass reporting: Muslim-group FPR", fontsize=10)
    axes[1].bar(["Clean", "Poisoned", "Defended"],
                [bd["trigger_evasion_clean"], bd["trigger_evasion_poisoned"], bd["trigger_evasion_after_defence"]],
                color=[C_BASE, "#b5534b", C_MIT])
    axes[1].set_title("Backdoor: toxic posts evading with trigger", fontsize=10)
    for a in axes:
        a.set_ylim(0, 1)
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig4_poisoning.png")); plt.close(fig)

    terms = sorted(id_weights, key=lambda t: -abs(id_weights[t]))[:14]
    fig, ax = plt.subplots(figsize=(8, 3.6))
    xt = np.arange(len(terms))
    ax.bar(xt - 0.2, [id_weights[t] for t in terms], 0.4, color=C_BASE, label="Baseline")
    ax.bar(xt + 0.2, [m_cda.word_weight(t) for t in terms], 0.4, color=C_MIT, label="Counterfactual aug.")
    ax.axhline(0, color="#555", lw=0.8)
    ax.set_xticks(xt, terms, rotation=35, ha="right")
    ax.set_ylabel("Model weight (+ pushes towards toxic)")
    ax.set_title("Global explanation: how much the identity words themselves drive the score", fontsize=10)
    ax.legend(frameon=False)
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig5_identity_weights.png")); plt.close(fig)

    ex = metrics["explainability"]["final"]
    fig, axes = plt.subplots(1, 2, figsize=(8.5, 3.2))
    meths = ["occlusion", "lime", "random"]
    axes[0].bar(meths, [ex[m]["token_f1"] for m in meths], color=[C_MIT, "#6b8f91", "#c9ccd1"])
    axes[0].set_title("Agreement with human rationales (token F1)", fontsize=10)
    axes[1].bar(meths, [ex[m]["comprehensiveness"] for m in meths], color=[C_MIT, "#6b8f91", "#c9ccd1"])
    axes[1].set_title("Comprehensiveness (score drop, top 20% removed)", fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(OUT, "fig6_explanations.png")); plt.close(fig)

    log("all results written to results/")


if __name__ == "__main__":
    main()
