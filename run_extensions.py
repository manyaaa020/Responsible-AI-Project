"""
Extensions to the main study (run after run_pipeline.py; about 3-4 minutes on a laptop CPU):

  1. 95% bootstrap confidence intervals for every group's false-positive rate
  2. In-processing mitigation with Fairlearn's ExponentiatedGradient
  3. Cross-check of our fairness metrics against Fairlearn's MetricFrame
  4. Annotator-disagreement analysis (bias in the labels themselves)
  5. A model card

Outputs in results/: extensions.json, extensions.md, model_card.md, fig7_fpr_confidence.png
"""
import json
import os
import time

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from src.adversarial import adversarial_augment  # noqa: E402
from src.data import GROUPS, load_hatexplain  # noqa: E402
from src.extensions import (annotator_disagreement, bootstrap_group_fpr, inprocessing_models,  # noqa: E402
                            metricframe_crosscheck, model_card)
from src.fairness import (apply_group_thresholds, bias_report, counterfactual_gap,  # noqa: E402
                          group_thresholds, matched_threshold, rescale)
from src.model import ModerationModel  # noqa: E402

OUT = "results"
LABEL = {"muslim": "Muslim", "jewish": "Jewish", "black": "Black", "white": "White",
         "lgbtq": "LGBTQ+", "women": "Women", "migrant": "Migrant", "asian_hispanic": "Asian/Hisp.",
         "background": "No group"}
T0 = time.time()


def sp(x):
    """Signed percentage points without a '-0'."""
    return f"{int(round(x * 100)):+d} pts"


def log(msg):
    print(f"[{time.time() - T0:6.1f}s] {msg}", flush=True)


def main():
    if not os.path.exists(os.path.join(OUT, "metrics.json")):
        raise SystemExit("Run `python run_pipeline.py` first.")
    metrics = json.load(open(os.path.join(OUT, "metrics.json")))
    df = load_hatexplain()
    tr, va, te = (df[df.split == s] for s in ("train", "val", "test"))

    # Same models and same operating point as run_pipeline.py
    base = ModerationModel().fit(tr.text, tr.toxic)
    bv = base.predict_proba(va.text)
    target = float((bv[((~va.any_identity) & (va.toxic == 0)).values] >= 0.5).mean())

    def calibrated(model, use_group_th):
        sv = model.predict_proba(va.text)
        t = matched_threshold(va, sv, target)
        sv, st = rescale(sv, t), rescale(model.predict_proba(te.text), t)
        th = group_thresholds(va, sv) if use_group_th else {g: 0.5 for g in GROUPS}
        return apply_group_thresholds(te, st, th)

    s_base = calibrated(base, False)
    at, ay = adversarial_augment(tr.text, tr.toxic, seed=1)
    final = ModerationModel(normalize=True).fit(list(tr.text) + at, list(tr.toxic) + ay)
    s_final = calibrated(final, True)
    log("baseline and final model rebuilt")

    ext = {}
    # 1 confidence intervals
    ext["bootstrap"] = bootstrap_group_fpr(te, {"baseline": s_base, "final": s_final}, B=1000)
    log("bootstrap confidence intervals done")

    # 2 in-processing
    rows = []
    for name, model, scores in [("Baseline", base, s_base), ("Final model (post-processing)", final, s_final)]:
        r = bias_report(te, scores)
        rows.append((name, model, r))
    for name, m in inprocessing_models(base, tr).items():
        s = calibrated(m, False)
        rows.append((f"In-processing: {name}", m, bias_report(te, s)))
        log(f"in-processing: {name}")
    ext["inprocessing"] = [{
        "model": n, "AUC": r["overall"]["auc"], "F1": r["overall"]["f1"],
        "Final bias score": r["overall"]["final_bias_score"], "Mean BPSN AUC": r["overall"]["pm_bpsn_auc"],
        "Max FPR gap": r["overall"]["max_fpr_gap"], "Jewish FPR": r["groups"]["jewish"]["fpr"],
        "Jewish FNR": r["groups"]["jewish"]["fnr"],
        "Counterfactual gap": counterfactual_gap(m, te[te.any_identity].text),
        "group_fpr": {g: v["fpr"] for g, v in r["groups"].items()},
    } for n, m, r in rows]

    # 3 MetricFrame cross-check
    ext["metricframe"] = metricframe_crosscheck(te, s_final)
    log("MetricFrame cross-check done")

    # 4 annotator disagreement
    ext["annotators"] = {"baseline": annotator_disagreement(te, s_base),
                         "final": annotator_disagreement(te, s_final)}
    log("annotator disagreement done")

    json.dump(ext, open(os.path.join(OUT, "extensions.json"), "w"), indent=2, default=float)

    # 5 model card
    model_card(metrics, ext, os.path.join(OUT, "model_card.md"))

    # ---------------------------------------------------------------- summary
    bs, imp = ext["bootstrap"], ext["bootstrap"]["improvement"]
    md = ["# Extension results\n", "Generated by `run_extensions.py` on the HateXplain test split.\n",
          "## 1. 95% confidence intervals for false-positive rates\n",
          "| Group | Harmless test posts | Baseline FPR (95% CI) | Final FPR (95% CI) | Change, 95% CI | Significant |",
          "|---|---|---|---|---|---|"]
    for g in GROUPS + ["background"]:
        if g not in bs["final"]:
            continue
        b, f, d = bs["baseline"][g], bs["final"][g], imp[g]
        md.append(f"| {LABEL[g]} | {f['n_harmless']} | {b['fpr']:.0%} ({b['lo']:.0%}-{b['hi']:.0%}) | "
                  f"{f['fpr']:.0%} ({f['lo']:.0%}-{f['hi']:.0%}) | {sp(-d['diff'])} ({sp(-d['hi'])} to {sp(-d['lo'])}) | "
                  f"{'yes' if d['significant'] else 'no'} |")
    md += ["\n## 2. In-processing (Fairlearn ExponentiatedGradient) vs our approach\n",
           "| Model | AUC | F1 | Final bias score | Mean BPSN AUC | Max FPR gap | Jewish FPR | Jewish FNR | Counterfactual gap |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in ext["inprocessing"]:
        md.append(f"| {r['model']} | {r['AUC']:.3f} | {r['F1']:.3f} | {r['Final bias score']:.3f} | "
                  f"{r['Mean BPSN AUC']:.3f} | {r['Max FPR gap']:.3f} | {r['Jewish FPR']:.0%} | {r['Jewish FNR']:.0%} | "
                  f"{r['Counterfactual gap']:.3f} |")
    mf = ext["metricframe"]
    md += [f"\n## 3. Cross-check with Fairlearn MetricFrame\n",
           f"Largest difference between our per-group FPR and Fairlearn's: {mf['max_abs_diff']:.6f}\n"]
    a, ab = ext["annotators"]["final"], ext["annotators"]["baseline"]
    md += ["\n## 4. Annotator disagreement\n",
           f"- Test posts where the 3 annotators split on toxic vs not: {a['share_split_all']:.0%}",
           f"- Final model error rate: unanimous posts {a['error_rate_unanimous']:.0%}, split posts {a['error_rate_split']:.0%}",
           f"- False-positive rate on harmless posts: unanimous {a['fpr_unanimous_harmless']:.0%}, split {a['fpr_split_harmless']:.0%}",
           f"- Split share: all harmless posts {a['split_share_harmless']:.0%}, among the final model's false positives {a['split_share_false_positives']:.0%}",
           f"- Harmless Jewish-mentioning posts ({a['jewish_harmless_n']}): {a['jewish_harmless_split_share']:.0%} split, vs {a['background_harmless_split_share']:.0%} for harmless posts naming no group",
           f"- Baseline for comparison: false positives that were split posts {ab['split_share_false_positives']:.0%}\n"]
    open(os.path.join(OUT, "extensions.md"), "w").write("\n".join(md))

    # ---------------------------------------------------------------- figure
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.spines.top": False,
                         "axes.spines.right": False, "figure.dpi": 150})
    gs = [g for g in GROUPS if g in bs["final"]]
    fig, ax = plt.subplots(figsize=(8, 4))
    y = np.arange(len(gs))
    for off, k, col, lab in [(-0.15, "baseline", "#9aa0a6", "Baseline"), (0.15, "final", "#2f6f73", "Final model")]:
        pts = [bs[k][g] for g in gs]
        ax.errorbar([p["fpr"] for p in pts], y + off,
                    xerr=[[p["fpr"] - p["lo"] for p in pts], [p["hi"] - p["fpr"] for p in pts]],
                    fmt="o", color=col, ecolor=col, capsize=3, label=lab)
    ax.axvline(bs["final"]["background"]["fpr"], color="#555", ls="--", lw=1)
    ax.set_yticks(y, [f"{LABEL[g]} (n={bs['final'][g]['n_harmless']})" for g in gs])
    ax.invert_yaxis()
    ax.set_xlabel("False-positive rate on harmless posts, with 95% bootstrap interval")
    ax.set_title("Only the Jewish-group improvement is clearly outside the noise", fontsize=10)
    ax.legend(frameon=False, loc="lower right")
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "fig7_fpr_confidence.png"))
    log("all extension results written to results/")


if __name__ == "__main__":
    main()
